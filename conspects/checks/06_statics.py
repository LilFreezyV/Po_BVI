# -*- coding: utf-8 -*-
"""Проверка всех чисел конспекта «Статика и гидростатика» (conspects/physics/06.html).

g = 10 м/с², ρ воды 1000 кг/м³. Равновесие проверяется прямым решением системы уравнений сил и
моментов или малым виртуальным перемещением; давление — численным интегрированием по поверхности.
"""
from math import atan, cos, degrees, pi, radians, sin, sqrt, tan

ok = 0
g, rho = 10, 1000


def check(name, got, want, rel=1e-3):
    global ok
    assert abs(got - want) <= rel * max(1, abs(want)), f'{name}: {got} ≠ {want}'
    ok += 1
    print(f'  ✓ {name}: {got:.6g}')


print('01 Правило моментов')
al = radians(60)
check('1.Р1 μ_min', 1 / (2 * tan(al)), 0.28868)
# моменты относительно нижнего конца: N₂ L sin α = mg (L/2) cos α; трение = N₂, N₁ = mg
m, L = 1, 1
N2 = m * g * L / 2 * cos(al) / (L * sin(al))
check('1.Р1 μ_min из моментов', N2 / (m * g), 0.28868)
check('1.С1 плечо', 30 * 0.2 / 10, 0.6)
# доска: моменты относительно правой опоры
left = (200 * 1 + 600 * 1.5) / 2
check('1.С2 левая опора', left, 550)
check('1.С2 правая опора', 800 - left, 250)
check('1.С2 моменты относительно левой', 250 * 2, 200 * 1 + 600 * 0.5)
check('1.С3 подкос (сжатие)', 100 / sin(radians(30)), 200)
check('1.С3 горизонтальный (растяжение)', 100 / tan(radians(30)), 173.21)
# узел: сумма сил = 0 (подкос толкает узел вверх-наружу под 30°, горизонтальный тянет к стене)
check('1.С3 баланс по горизонтали', 200 * cos(radians(30)) - 173.205, 0, 1e-3)
check('1.С3 баланс по вертикали', 200 * sin(radians(30)) - 100, 0)

print('02 Виртуальные перемещения')
check('2.Р1 сила', 600 / 4, 150)
check('2.С1 ворот', 500 * 0.1 / 0.5, 100)
check('2.С2 домкрат', 10000 * 0.005 / (2 * pi * 0.3), 26.526)
a, th, d = 1.0, radians(30), 1e-7
y = lambda t: 2 * a * sin(t)                                    # noqa: E731
x = lambda t: 2 * a * cos(t)                                    # noqa: E731
F = 10 * (y(th + d) - y(th - d)) / (x(th - d) - x(th + d))
check('2.С3 сила (виртуальное перемещение), кН', F, 17.321)
check('2.С3 mg ctg θ', 10 / tan(th), 17.321)
check('канат: натяжение у концов', 100 / (2 * sin(radians(30))), 100)
check('канат: натяжение внизу', 100 / (2 * tan(radians(30))), 86.603)

print('03 Гидростатика')
check('3.Р1 доля в воде', (900 - 800) / (1000 - 800), 0.5)
check('3.С1 давление', 1e5 + rho * g * 10, 2e5)
check('3.С2 сила', rho * g * 25 * 10 / 2, 1.25e6)
n = 200000
Fs = sum(rho * g * (5 - 5 * (i + 0.5) / n) * 10 * 5 / n for i in range(n))
mom = sum(rho * g * (5 - 5 * (i + 0.5) / n) * 10 * 5 / n * (5 * (i + 0.5) / n) for i in range(n))
check('3.С2 сила (интеграл)', Fs, 1.25e6, 1e-6)
check('3.С2 точка приложения от дна', mom / Fs, 5 / 3, 1e-5)
H, R = 1, 0.2
form = rho * g * (H * pi * R * R - 2 * pi * R ** 3 / 3)
check('3.С3 формула', form, 1089.1)
# численно: вертикальная составляющая давления по поверхности полусферы (кольца по полярному углу)
Fz = 0
for i in range(n):
    t = pi / 2 * (i + 0.5) / n                                   # угол от вершины
    z = R * cos(t)                                               # высота над основанием
    dA = 2 * pi * R * sin(t) * R * (pi / 2 / n)
    Fz += rho * g * (H - z) * dA * cos(t)
check('3.С3 сила (интеграл по поверхности)', Fz, form, 1e-6)

print('04 Ускоренные сосуды')
check('4.Р1 угол', degrees(atan(2 / g)), 11.310)
check('4.Р1 разность уровней', 5 * 2 / g, 1)
check('4.С1 угол нити', degrees(atan(3 / g)), 16.699)
check('4.С2 перепад', 100 * 0.01 / (2 * g), 0.05)
check('4.С3 давление', rho * (g + 2) * 0.3, 3600)
check('4.С3 натяжение', (1000 - 500) * 1e-4 * (g + 2), 0.6)

print(f'\nВсе проверки пройдены: {ok}')
