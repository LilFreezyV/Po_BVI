def check(name, got, want, rel=1e-3):
    global ok
    assert abs(got - want) <= rel * max(1e-30, abs(want)), f'{name}: {got} ≠ {want}'
    ok += 1
    print(f'  ✓ {name}: {got:.6g}')


def heat_along(P, V1, V2, i=3, n=200000):
    """Теплота по малым шагам вдоль процесса P(V) для ν = 1: δQ = (i/2) d(PV) + P dV."""
    Q, Qin, Qout, A = 0.0, 0.0, 0.0, 0.0
    for k in range(n):
        a = V1 + (V2 - V1) * k / n; b = V1 + (V2 - V1) * (k + 1) / n
        dA = (P(a) + P(b)) / 2 * (b - a); dU = i / 2 * (P(b) * b - P(a) * a)
        q = dU + dA; Q += q; A += dA
        if q > 0: Qin += q
        else: Qout -= q
    return Q, Qin, Qout, A


