check('5.С2 наибольший угол', degrees(atan(1 / sqrt(3))), 30)
# 5.С2 перебором: упругий удар m₁ = 2, m₂ = 1, все направления удара
best = 0
for i in range(1, 20000):
    phi = pi / 2 * i / 20000                                   # угол линии удара с направлением v
    n = (cos(phi), sin(phi))
    J = 2 * 2 * 1 / 3 * (1 * n[0])                             # импульс по линии центров при v = (1, 0)
    v1 = (1 - J / 2 * n[0], -J / 2 * n[1])
    best = max(best, degrees(atan(abs(v1[1]) / v1[0])) if v1[0] > 0 else 90)
check('5.С2 наибольший угол (перебор)', best, 30, 1e-3)
