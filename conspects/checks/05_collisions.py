def galperin(ratio):
    """Число соударений: шар M (скорость −1) налетает на шар m у стенки."""
    V, v, n = -1.0, 0.0, 0
    while True:
        if V < v:                                               # большой догоняет маленький
            V, v = elastic(ratio, V, 1, v); n += 1
        elif v < 0:                                             # маленький летит к стенке
            v = -v; n += 1
        else:
            return n


check('6.С3 соударений при M/m = 100', galperin(100), 31)
check('6.С3 соударений при M/m = 10 000', galperin(10000), 314)

