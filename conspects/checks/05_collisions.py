"""Проверка всех чисел конспекта «Удары» (conspects/physics/05.html).

g = 10 м/с². Удары проверяются прямым моделированием (пружина в месте контакта, суммирование
отскоков, перебор соударений) или законами сохранения, записанными отдельно от формул.
"""
from math import atan, cos, degrees, hypot, pi, radians, sin, sqrt, tan

ok = 0
g = 10


def check(name, got, want, rel=1e-3):
    global ok
    assert abs(got - want) <= rel * max(1, abs(want)), f'{name}: {got} ≠ {want}'
    ok += 1
    print(f'  ✓ {name}: {got:.6g}')


def elastic(m1, v1, m2, v2):
    return ((m1 - m2) * v1 + 2 * m2 * v2) / (m1 + m2), ((m2 - m1) * v2 + 2 * m1 * v1) / (m1 + m2)


def spring_collision(m1, v1, m2, v2, k=1e4, dt=1e-6):
    """Удар как сжатие очень жёсткой пружины: возвращает скорости после и наибольшее сжатие."""
    x1, x2, comp = 0.0, 0.0, 0.0
    while True:
        f = k * max(x1 - x2, 0)
        v1 -= f / m1 * dt; v2 += f / m2 * dt; x1 += v1 * dt; x2 += v2 * dt
        comp = max(comp, x1 - x2)
        if x1 - x2 < 0 and v1 <= v2:
            return v1, v2, comp


print('01 Парадокс большого тела')
check('1.Р1 v₁′', elastic(1, 6, 2, 0)[0], -2)
check('1.Р1 v₂′', elastic(1, 6, 2, 0)[1], 4)
u1, u2, _ = spring_collision(1, 6, 2, 0)
check('1.Р1 v₁′ (моделирование)', u1, -2, 1e-4)
check('1.Р1 v₂′ (моделирование)', u2, 4, 1e-4)
check('1.С1 равные массы: v₂′', elastic(1, 5, 1, 0)[1], 5)
check('1.С2 доля энергии', 4 * 1 * 100 / 101 ** 2, 0.039212)
v = sqrt(2 * g * 1)
_, small = elastic(0.6, v, 0.06, -v)                             # большой отскочил от пола и встретил малый
check('1.С3 скорость малого мяча / v', small / v, 2.6364)
check('1.С3 высота, м', (small / v) ** 2 * 1, 6.9504)
check('1.С3 предел M ≫ m: 9h', elastic(1e9, v, 1, -v)[1] ** 2 / v ** 2, 9, 1e-6)

print('02 Удар о стенку')
check('2.Р1 отскок', 10 + 2 * 2, 14)
check('2.Р1 (моделирование тяжёлой стенкой)', -spring_collision(1, 10, 1e7, -2, k=1e6)[0], 14, 1e-4)
check('2.С1 отскок от удаляющейся', -spring_collision(1, 10, 1e7, 2, k=1e6)[0], 6, 1e-4)
check('2.С2 общая скорость', 2 * 3 / 3, 2)
check('2.С2 потери', 2 * 9 / 2 - 3 * 4 / 2, 3)
e, h = 0.8, 1.25
S, T, hh, v = h, sqrt(2 * h / g), h, sqrt(2 * g * h)
for _ in range(2000):
    v *= e; hh = v * v / (2 * g); S += 2 * hh; T += 2 * v / g
check('2.С3 путь (сумма отскоков)', S, h * (1 + e * e) / (1 - e * e), 1e-6)
check('2.С3 путь', h * (1 + e * e) / (1 - e * e), 5.6944)
check('2.С3 время (сумма)', T, 4.5, 1e-6)

print('03 Удар с трением')
v, a, mu = 10, radians(45), 0.2
vn, vt = v * cos(a), v * sin(a)
vt2 = vt - mu * 2 * vn
check('3.Р1 касательная после', vt2, 4.2426)
check('3.Р1 скорость после', hypot(vn, vt2), 8.2462)
check('3.Р1 угол с нормалью', degrees(atan(vt2 / vn)), 30.964)
check('3.С1 касательная гасится, μ=1: остаётся нормальная', vn, 7.0711)
check('3.С2 μ_min', tan(radians(30)) / 2, 0.28868)
check('3.С3 горизонтальная скорость', 0.1 * 2 * 5, 1)
check('3.С3 угол с вертикалью', degrees(atan(1 / 5)), 11.310)

