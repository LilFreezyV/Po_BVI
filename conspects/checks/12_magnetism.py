from math import atan, cos, exp, hypot, log, pi, sin, sqrt

ok = 0
mu0, e, me, mp, g = 4 * pi * 1e-7, 1.6e-19, 9.11e-31, 1.67e-27, 10


def check(name, got, want, rel=1e-3):
    global ok
    assert abs(got - want) <= rel * max(1e-30, abs(want)), f'{name}: {got} ≠ {want}'
    ok += 1
    print(f'  ✓ {name}: {got:.6g}')


def biot(points, I, P):
    """Поле в точке P от ломаной points (замкнутость задаётся повтором первой точки)."""
    Bx = By = Bz = 0.0
    for (x1, y1, z1), (x2, y2, z2) in zip(points, points[1:]):
        dl = (x2 - x1, y2 - y1, z2 - z1); m = ((x1 + x2) / 2, (y1 + y2) / 2, (z1 + z2) / 2)
        r = (P[0] - m[0], P[1] - m[1], P[2] - m[2]); rr = sqrt(r[0] ** 2 + r[1] ** 2 + r[2] ** 2)
        c = mu0 * I / (4 * pi * rr ** 3)
        Bx += c * (dl[1] * r[2] - dl[2] * r[1]); By += c * (dl[2] * r[0] - dl[0] * r[2]); Bz += c * (dl[0] * r[1] - dl[1] * r[0])
    return Bx, By, Bz


