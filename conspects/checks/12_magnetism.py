check('1.С2 квадрат', 2 * sqrt(2) * mu0 * 10 / (pi * 0.2), 5.6569e-5)
check('1.С2 квадрат (сумма)', biot(sqf, 10, (0, 0, 0))[2], 5.6569e-5, 1e-5)
check('1.С3 шпилька', mu0 * 10 / (4 * 0.1) * (1 + 2 / pi), 5.1416e-5)
hair = [(-1000, 0.1, 0)] + [(-1000 + 1000 * k / 100000, 0.1, 0) for k in range(1, 100001)]
