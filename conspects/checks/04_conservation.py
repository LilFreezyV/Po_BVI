# -*- coding: utf-8 -*-
"""Проверка всех чисел конспекта «Законы сохранения» (conspects/physics/04.html).

g = 10 м/с². Ответы получены вторым способом: моделированием, численным интегрированием
или из другого закона сохранения.
"""
from math import cos, exp, log, radians, sin, sqrt, tan

ok = 0
g = 10


def check(name, got, want, rel=1e-3):
    global ok
    assert abs(got - want) <= rel * max(1, abs(want)), f'{name}: {got} ≠ {want}'
    ok += 1
    print(f'  ✓ {name}: {got:.6g}')


print('01 Импульс')
check('1.Р1 скорость тележки', 60 * 2 / 40, 3)
check('1.С1 изменение импульса', 0.5 * 10 * 2, 10)
check('1.С1 средняя сила', 10 / 0.02, 500)
check('1.С2 второй осколок', (10 * 200 + 4 * 100) / 6, 400)
ratio = exp(3 / 2)
check('1.С3 m₀/m', ratio, 4.4817)
check('1.С3 доля топлива', 1 - 1 / ratio, 0.77687)
# ракета, выбрасывающая топливо малыми порциями со скоростью u относительно себя
m, v, u, dm = 1.0, 0.0, 2.0, 1e-6
while v < 3:
    v += dm * u / (m - dm)          # ЗСИ в системе ракеты: (m − dm)·Δv = dm·u
    m -= dm
check('1.С3 доля топлива (моделирование порциями)', 1 - m, 0.77687, 1e-4)

print('02 Работа и мощность')
check('2.Р1 работа', 200 * (0.3 ** 2 - 0.1 ** 2) / 2, 8)
n = 100000
A = sum(200 * (0.1 + 0.2 * (i + 0.5) / n) * 0.2 / n for i in range(n))
check('2.Р1 работа (площадь под графиком)', A, 8, 1e-6)
check('2.С1 работа', 0.3 * 10 * g * 5, 150)
check('2.С2 максимальная скорость', 60e3 / 2e3, 30)
# цепь: поднять вертикально — центр масс на L/2
m, L = 4, 2
A = sum(m / n * g * (L * (i + 0.5) / n) for i in range(n))
check('2.С3 работа (сумма по звеньям)', A, 40, 1e-6)

print('03 Теорема о кинетической энергии')
check('3.Р1 тормозной путь', 20 ** 2 / (2 * 0.5 * g), 40)
check('3.С1 работа сопротивления', 0.01 * (200 ** 2 - 400 ** 2) / 2, -600)
h, al, mu = 5, radians(30), 0.1
check('3.С2 путь по горизонтали', h / mu - h / tan(al), 41.340)
check('3.С2 энергия сходится', g * h - mu * g * cos(al) * h / sin(al) - mu * g * (h / mu - h / tan(al)), 0)
per = (400 ** 2 - 300 ** 2) / 2
check('3.С3 досок (дробно)', 400 ** 2 / 2 / per, 2.2857)

print('04 Задачи на кинетическую энергию')
h, al, mu = 1, radians(30), 0.2
v = sqrt(2 * g * h * (1 - mu / tan(al)))
check('4.Р1 скорость внизу', v, 3.6154)
# моделирование соскальзывания
a = g * (sin(al) - mu * cos(al)); s = h / sin(al)
check('4.Р1 скорость (через ускорение)', sqrt(2 * a * s), v)
check('4.С1 скорость падения', sqrt(100 + 2 * g * 10), 17.321)
ve = sqrt(16 - 2 * 0.3 * g * 2)
check('4.С2 скорость у края', ve, 2)
check('4.С2 скорость у пола', sqrt(ve ** 2 + 2 * g * 0.8), 4.4721)
x, v, dt = 0.0, 0.0, 1e-5
vmax = 0
while x < 6:
    v += (10 - 2 * x) * dt; x += v * dt
    vmax = max(vmax, v)
check('4.С3 наибольшая скорость (моделирование)', vmax, 7.0711, 1e-4)

print('05 Механическая энергия')
m, k, h = 0.1, 100, 0.5
x = (m * g + sqrt((m * g) ** 2 + 2 * k * m * g * h)) / k
check('5.Р1 сжатие', x, 0.11050)
check('5.Р1 энергия', m * g * (h + x), k * x * x / 2)
check('5.С1 скорость', sqrt(200 / 0.01) * 0.05, 7.0711)
x0 = m * g / k
check('5.С2 наибольшая скорость', sqrt(2 * g * (h + x0) - k * x0 ** 2 / m), 3.1780)
# 5.С3: брусок на пружине с сухим трением — моделирование
m, k, mu = 1, 100, 0.2
x, v, dt, path, stops = 0.1, 0.0, 1e-6, 0.0, []
while True:
    if v == 0:
        if abs(k * x) <= mu * m * g + 1e-9:
            break
        sgn = -1 if x > 0 else 1                       # поедет к положению равновесия
    else:
        sgn = 1 if v > 0 else -1
    a = (-k * x - mu * m * g * (1 if (v > 0 or (v == 0 and sgn > 0)) else -1)) / m
    v_new = v + a * dt
    if v != 0 and v_new * v < 0:
        stops.append(x); v = 0.0; continue
    x += v_new * dt; path += abs(v_new * dt); v = v_new
check('5.С3 первая остановка', stops[0], -0.06, 1e-3)
check('5.С3 окончательное положение', x, 0.02, 1e-3)
check('5.С3 путь', path, 0.24, 1e-3)
check('5.С3 энергия ушла в тепло', k * (0.1 ** 2 - 0.02 ** 2) / 2, mu * m * g * 0.24)

print('06 Скатывание по окружности')
R = 0.4
check('6.Р1 наименьшая высота', 2.5 * R, 1.0)
check('6.Р1 N внизу / mg', (2 * g * 2.5 * R / R + g) / g, 6)
check('6.С1 N вверху / mg', (2 * g * (3 * R - 2 * R) / R - g) / g, 1)
check('6.С2 T внизу / mg', (2 * g * 1 / 1 + g) / g, 3)
# 6.С3: отрыв на высоте 1,5R; h — высота старта
hh = 1.75 * R
sb = 0.5
v2 = 2 * g * (hh - R - R * sb)
check('6.С3 условие отрыва v² = gR sin β', v2, g * R * sb)
# перебором угла φ от нижней точки: N/m = v²/R + g cos φ обращается в ноль
from math import pi  # noqa: E402
phi = 0.0
while True:
    vv = 2 * g * (hh - R * (1 - cos(phi)))
    if vv / R + g * cos(phi) <= 0: break
    phi += 1e-6
check('6.С3 высота отрыва (перебор), в R', (1 - cos(phi)), 1.5, 1e-4)

print('07 Наезд на горку')
m, M, v = 1, 4, 5
check('7.Р1 высота', M * v * v / (2 * g * (M + m)), 1)
check('7.С1 общая скорость', m * v / (m + M), 1)
check('7.С2 скорость шайбы', (m - M) / (m + M) * v, -3)
check('7.С2 скорость горки', 2 * m * v / (m + M), 2)
check('7.С2 импульс', m * -3 + M * 2, m * v)
check('7.С2 энергия', m * 9 / 2 + M * 4 / 2, m * v * v / 2)
check('7.С3 наименьшая скорость', sqrt(2 * g * 0.9 * (M + m) / M), 4.7434)

print('08 Практикум')
vb = sqrt(2 * g * 0.05)
check('8.Р1 скорость бруска', vb, 1)
check('8.Р1 скорость пули', (1 + 0.01) / 0.01 * vb, 101)
check('8.Р1 доля в тепло', 1 / 1.01, 0.990099)
check('8.С1 энергия', 1 * 2 ** 2 / 2 + 2 * 1 ** 2 / 2, 3)
mu_r = 1 * 2 / 3
check('8.С2 сжатие', sqrt(2 * (mu_r * 9 / 2) / 200), 0.17321)
# 8.С2 моделированием: сближение брусков с пружиной
x1, v1, x2, v2, dt, comp = 0.0, 3.0, 0.0, 0.0, 1e-6, 0
while True:
    f = 200 * max(x1 - x2, 0)
    v1 -= f / 1 * dt; v2 += f / 2 * dt; x1 += v1 * dt; x2 += v2 * dt
    comp = max(comp, x1 - x2)
    if v1 <= v2: break
check('8.С2 сжатие (моделирование)', comp, 0.17321, 1e-4)
m, M, h = 0.1, 0.4, 0.5
v = sqrt(2 * g * h * M / (M + m))
check('8.С3 скорость шайбы', v, 2.8284)
check('8.С3 скорость горки', m * v / M, 0.70711)
check('8.С3 энергия', m * v * v / 2 + M * (m * v / M) ** 2 / 2, m * g * h)

print('09 Качение, теорема Кёнига')
check('9.Р1 скорость обруча', sqrt(g * 0.9), 3)
check('9.С1 энергия', 2 * 3 ** 2, 18)
check('9.С2 ускорение', g * sin(radians(30)) / 2, 2.5)
# 9.С2 через динамику: Ma = Mg sin α − F, F·R = I·ε = M R² a / R → F = Ma
check('9.С2 через силу трения', g * sin(radians(30)) - g * sin(radians(30)) / 2, 2.5)
check('9.С3 ускорение', g / 2, 5)
check('9.С3 натяжение', 1 * (g - 5), 5)

print(f'\nВсе проверки пройдены: {ok}')
