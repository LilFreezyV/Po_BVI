# -*- coding: utf-8 -*-
"""Проверка всех чисел конспекта «Электростатика» (conspects/physics/10.html).

k = 9·10⁹, ε₀ = 8,85·10⁻¹², e = 1,6·10⁻¹⁹ Кл, mₑ = 9,11·10⁻³¹ кг, mₚ = 1,67·10⁻²⁷ кг, g = 10.
Поля проверяются прямым суммированием по малым зарядам, движение — интегрированием.
"""
from math import asin, atan, cos, degrees, exp, hypot, pi, sin, sqrt, tan

ok = 0
k, e0, e, me, mp, g = 9e9, 8.85e-12, 1.6e-19, 9.11e-31, 1.67e-27, 10


def check(name, got, want, rel=1e-3):
    global ok
    assert abs(got - want) <= rel * max(1e-30, abs(want)), f'{name}: {got} ≠ {want}'
    ok += 1
    print(f'  ✓ {name}: {got:.6g}')


print('01 Кулон')
x = 0.3 * 2 / 3
check('1.Р1 положение', x, 0.2)
check('1.Р1 равновесие', 4 / x ** 2, 1 / (0.3 - x) ** 2)
check('1.С1 сила', k * 1e-6 * 2e-6 / 0.01, 1.8)
t = 0.05 / sqrt(1 - 0.05 ** 2)
q = sqrt(1e-4 * g * t * 0.01 / k)
check('1.С2 заряд, нКл', q * 1e9, 7.4582)
check('1.С3 Q/q', -(sqrt(2) + 0.5) / 2, -0.95711)
# 1.С3 прямым сложением сил на заряд в вершине (1,1) квадрата со стороной 1 (центр в 0,5;0,5)
fx = 1 / 1 + 1 / 2 ** 1.5                                         # от (0,1) по x и от (0,0) по диагонали
check('1.С3 сила от трёх зарядов (в kq²/a²)', hypot(fx, fx), sqrt(2) + 0.5)

print('02 Напряжённость')
E1 = k * 1e-9 / (0.01 + 0.01)
check('2.Р1 поле', 2 * E1 * 0.1 / sqrt(0.02), 636.40)
check('2.С1 поле', k * 5e-9 / 0.09, 500)
check('2.С2 поле', k * 1e-9 / 0.005, 1800)
check('2.С3 расстояние от −q', 0.1, 0.1)
check('2.С3 поле ноль', 4 / 0.2 ** 2, 1 / 0.1 ** 2)

print('03 Кольцо, нить')
Q, R = 1e-8, 0.1
z = R / sqrt(2)
Emax = k * Q * z / (R * R + z * z) ** 1.5
check('3.Р1 наибольшее поле', Emax, 3464.1)
n = 20000
Es = sum(k * Q / n * z / (R * R + z * z) ** 1.5 for _ in range(1))  # симметрия: осевая проекция
Ez = 0
for i in range(n):                                                # суммирование по точкам кольца
    a = 2 * pi * i / n
    dx, dy, dz = -R * cos(a), -R * sin(a), z
    r = sqrt(dx * dx + dy * dy + dz * dz)
    Ez += k * Q / n * dz / r ** 3
check('3.Р1 поле (сумма по кольцу)', Ez, Emax, 1e-6)
best = max(k * Q * (zz / 1e4) / (R * R + (zz / 1e4) ** 2) ** 1.5 for zz in range(1, 5000))
check('3.Р1 максимум перебором', best, Emax, 1e-5)
check('3.С2 нить', 2 * k * 1e-9 / 0.1, 180)
Ex = sum(k * 1e-9 / n / 0.01 * sin(pi * (i + 0.5) / n) for i in range(n))
check('3.С3 полукольцо (сумма)', Ex, 2 * k * 1e-9 / (pi * 0.01), 1e-6)
check('3.С3 полукольцо', 2 * k * 1e-9 / (pi * 0.01), 572.96)

print('04 Гаусс')
check('4.Р1 поток через грань', 1e-9 / (6 * e0), 18.832)
check('4.С1 полный поток', 1e-9 / e0, 112.99)
check('4.С2 через дальнюю грань', 1e-9 / (24 * e0), 4.7081)
check('4.С3 через круг', 1e-9 / (2 * e0) * (1 - 1 / sqrt(2)), 16.548)
# 4.С3 суммированием потока через кольца круга
F = 0
for i in range(n):
    r = (i + 0.5) / n * 0.1
    F += k * 1e-9 / (0.01 + r * r) * 0.1 / sqrt(0.01 + r * r) * 2 * pi * r * 0.1 / n
check('4.С3 поток (сумма; k = 9·10⁹ против 1/4πε₀ — 0,1 %)', F, 16.548, 2e-3)

print('05 Поля по Гауссу')
check('5.Р1 внутри', k * 1e-9 * 0.05 / 0.001, 450)
check('5.Р1 снаружи', k * 1e-9 / 0.04, 225)
check('5.С1 плоскость', 1e-9 / (2 * e0), 56.497)
check('5.С2 между плоскостями', 1e-9 / e0, 112.99)
check('5.С3 полость', 1e-6 * 0.05 / (3 * e0), 1883.2)

print('06 Плоский заряд')
s = 1e-8
check('6.Р1 диск', k * s * 2 * pi * (1 - 1 / sqrt(2)), 165.62)
# 6.Р1 суммированием по кольцам диска
Ed = sum(k * s * 2 * pi * ((i + 0.5) / n * 0.1) * (0.1 / n) * 0.1 / (0.01 + ((i + 0.5) / n * 0.1) ** 2) ** 1.5 for i in range(n))
check('6.Р1 диск (сумма)', Ed, 165.62, 1e-4)
check('6.С1 плоскость', 2 * pi * k * s, 565.49)
check('6.С2 грань куба', k * s * 2 * pi / 3, 188.50)
check('6.С3 три грани', sqrt(3) * k * s * 2 * pi / 3, 326.49)
# 6.С2 суммированием по квадрату: грань со стороной 1, точка на расстоянии 0,5 от центра
m = 600
Eq = 0
for i in range(m):
    for j in range(m):
        x = (i + 0.5) / m - 0.5; y = (j + 0.5) / m - 0.5
        Eq += k * s * (1 / m) ** 2 * 0.5 / (x * x + y * y + 0.25) ** 1.5
check('6.С2 грань (сумма)', Eq, 188.50, 1e-4)

print('07 Потенциал')
v = sqrt(2 * e * 100 / me)
check('7.Р1 скорость электрона', v, 5.9271e6)
check('7.С1 потенциал', 4 * k * 1e-9 / (0.1 / sqrt(2)), 509.12)
check('7.С2 потенциал в центре кольца', k * 1e-8 / 0.1, 900)
check('7.С2 скорость протона', sqrt(2 * e * 900 / mp), 4.1526e5)
check('7.С3 центр шара', 1.5 * k * 1e-9 / 0.1, 135)

print('08 Энергия')
check('8.Р1 треугольник', 3 * k * 1e-12 / 0.1, 0.27)
check('8.С1 пара', k * 1e-12 / 0.1, 0.09)
check('8.С2 квадрат', k * 1e-12 / 0.1 * (4 + sqrt(2)), 0.48728)
check('8.С3 из центра', 4 * sqrt(2) * k * 1e-12 / 0.1, 0.50912)

print('09 Электромеханика')
W = k * 1e-12 / 0.1
check('9.Р1 скорости', sqrt(W / 1e-3), 9.4868)
check('9.С1 один закреплён', sqrt(2 * W / 1e-3), 13.416)
check('9.С2 сближение', k * 1e-12 / (1e-3 * 100 / 2), 0.18)
check('9.С3 оба свободны', k * 1e-12 / (0.5e-3 * 100 / 2), 0.36)
# 9.С3 моделированием
x1, x2, v1, v2, dt, rmin = 0.0, 5.0, 10.0, 0.0, 1e-6, 10
while v1 > v2:
    F = k * 1e-12 / (x2 - x1) ** 2
    v1 -= F / 1e-3 * dt; v2 += F / 1e-3 * dt; x1 += v1 * dt; x2 += v2 * dt
    rmin = min(rmin, x2 - x1)
# старт с 5 м: часть энергии уже в поле, поправка на начальное расстояние
check('9.С3 сближение (моделирование, со старта 5 м)', rmin, 1 / (1 / 0.36 + 1 / 5), 1e-3)

print('10 Проводники')
check('10.Р1 φ₂', k * 1e-9 / 0.2, 45)
check('10.Р1 φ₁', k * 2e-9 / 0.1 - k * 1e-9 / 0.2, 135)
check('10.С1 ёмкость, пФ', 4 * pi * e0 * 0.1 * 1e12, 11.121)
check('10.С2 заряд, нКл', 1 * 0.1 / 0.2, 0.5)
C1, C3 = 4 * pi * e0 * 0.1, 4 * pi * e0 * 0.3
check('10.С3 потери', 9e-18 / (2 * C1) - 9e-18 / (2 * C3), 2.6978e-7)

print('11 Изображения')
check('11.Р1 сила', k * 1e-12 / 0.04, 0.225)
check('11.С2 работа', k * 1e-12 / 0.4, 0.0225)
check('11.С3 плотность', -1e-6 / (2 * pi * 0.01), -1.5915e-5)
# 11.С3: полный индуцированный заряд суммированием σ(r) = −q h / (2π (r² + h²)^{3/2})
tot = sum(-1e-6 * 0.1 / (2 * pi * (r * r + 0.01) ** 1.5) * 2 * pi * r * 1e-3 for r in [(i + 0.5) * 1e-3 for i in range(200000)])
check('11.С1 индуцированный заряд (сумма до 200 м)', tot, -1e-6, 1e-3)

print('12 Пластины')
check('12.Р1 внешние', (3 - 1) / 2, 1)
check('12.Р1 внутренние', 3 - 1, 2)
check('12.С3 сила', 3e-9 * 1e-9 / (2 * e0 * 0.01), 1.6949e-5)

print('13 Полёт пластин')
E = 1e-8 / (e0 * 0.01)
check('13.Р1 поле', E, 1.1299e5)
W = 1e-9 * E * 0.01
check('13.Р1 энергия', W, 1.1299e-6)
check('13.Р1 скорость', sqrt(2 * W / 1e-3), 0.047537)
check('13.С1 сила', 1e-9 * E, 1.1299e-4)
check('13.С2 время', sqrt(2 * 0.005 / (1e-9 * E / 1e-3)), 0.29749)
check('13.С3 сила', 1e-16 / (2 * e0 * 0.01), 5.6497e-4)

print('14 Частицы в конденсаторе')
a = e * 2000 / me; t = 0.05 / 1e7
check('14.Р1 отклонение, см', a * t * t / 2 * 100, 0.43908)
check('14.Р1 угол', degrees(atan(a * t / 1e7)), 9.9597)
check('14.С1 ускорение протона', e * 1e4 / mp, 9.5808e11)
check('14.С2 наибольшее напряжение', 20 * 0.5 / 0.43908, 22.774)
check('14.С3 напряжение', 100 * sin(radians := pi / 4) ** 2, 50)

print('15 Соединения')
check('15.Р1 напряжение', 200 / 5, 40)
check('15.Р1 потери', 2e-6 * 1e4 / 2 - 5e-6 * 1600 / 2, 0.006)
check('15.С1 ёмкость, пФ', e0 * 0.01 / 1e-3 * 1e12, 88.5)
check('15.С2 ёмкость', 2 * 3 / 5, 1.2)
check('15.С3 напряжение', (200 - 150) / 5, 10)
check('15.С3 потери', 2e-6 * 1e4 / 2 + 3e-6 * 2500 / 2 - 5e-6 * 100 / 2, 0.0135)
# 15.Р1 перетеканием через резистор: тепло ∫I²R dt не зависит от R
for Rr in (10.0, 1000.0):
    tau = Rr * 1.2e-6                                            # RC с последовательной ёмкостью
    q1, q2, Q, dt = 200e-6, 0.0, 0.0, tau / 5000
    for _ in range(100000):
        I = (q1 / 2e-6 - q2 / 3e-6) / Rr
        Q += I * I * Rr * dt; q1 -= I * dt; q2 += I * dt
    check(f'15.Р1 тепло в резисторе {Rr:.0f} Ом', Q, 0.006, 2e-3)

print('16 Сложные конденсаторы')
c = e0 * 0.01 / 1e-3
check('16.Р1 заряд', 2 * c * 100, 1.77e-8)
check('16.С1 заряд', c * 100, 8.85e-9)
check('16.С2 заряд', 3 * c * 100, 2.655e-8)
check('16.С3 заряд', 1.5 * c * 100, 1.3275e-8)

print('17 Практикум: пластины')
c2 = e0 * 0.01 / 2e-3
check('17.Р1 ёмкость, пФ', e0 * 0.01 / 1e-3 * 1e12, 88.5)
check('17.С2 работа поля', 1e-16 / (2 * c2) - 1e-16 / (2 * 2 * c2), 5.6497e-7)
check('17.С3 работа поля', 2 * c2 * 1e4 / 2 - c2 * 1e4 / 2, 2.2125e-7)
check('17.С3 работа батареи', (2 * c2 - c2) * 100 * 100, 4.425e-7)

print('18 Диэлектрики')
check('18.Р1 ёмкость, пФ', e0 * 0.01 / (1e-3 + 1e-3 / 7) * 1e12, 77.438)
check('18.С2 во сколько раз', (1 + 7) / 2, 4)
check('18.С3 связанный заряд, нКл', 10 * (1 - 1 / 7), 8.5714)

print('19 Электрическое давление')
check('19.Р1 сила', 1e-16 / (2 * e0 * 0.01), 5.6497e-4)
check('19.С1 давление', e0 * 1e12 / 2, 4.425)
check('19.С2 сила', e0 * 0.01 * 1e6 / (2 * 1e-6), 0.04425)
sq = sqrt(2 * e0 * 4 * 0.04 / 0.02)
check('19.С3 плотность заряда', sq, 1.1899e-5)
check('19.С3 заряд', sq * 4 * pi * 0.02 ** 2, 5.9810e-8)

print(f'\nВсе проверки пройдены: {ok}')
