def sphere_trace(y0, d, R, n1, n2):
    """Луч из осевой точки на расстоянии d перед вершиной (x = 0) сферы радиуса R (центр x = R)
    под малым углом; точный Снеллиус; возвращает точку пересечения с осью после поверхности."""
    u = y0 / d                                                    # наклон луча
    # пересечение луча y = u (x + d) с окружностью (x − R)² + y² = R²
    A_, B_, C_ = 1 + u * u, 2 * (u * u * d - R), u * u * d * d
    x = (-B_ - sqrt(B_ * B_ - 4 * A_ * C_)) / (2 * A_); y = u * (x + d)
    nx, ny = (x - R) / R, y / R                                   # нормаль наружу (к источнику)
    dx, dy = 1 / sqrt(1 + u * u), u / sqrt(1 + u * u)
    c1 = -(nx * dx + ny * dy); r = n1 / n2
    c2 = sqrt(1 - r * r * (1 - c1 * c1))
    tx, ty = r * dx + (r * c1 - c2) * nx, r * dy + (r * c1 - c2) * ny
    return x - y * tx / ty


