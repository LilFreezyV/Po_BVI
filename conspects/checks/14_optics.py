# 15.С2: стеклянный шар, точная трассировка параксиального луча (векторный закон Снеллиуса)
def refract(d, nrm, n1, n2):
    """d — направление луча, nrm — единичная нормаль, обращённая навстречу лучу."""
    ci = -(d[0] * nrm[0] + d[1] * nrm[1]); r = n1 / n2; k = 1 - r * r * (1 - ci * ci)
    return (r * d[0] + (r * ci - sqrt(k)) * nrm[0], r * d[1] + (r * ci - sqrt(k)) * nrm[1])


R, n, y = 1.0, 1.5, 1e-4
P0 = (-sqrt(R * R - y * y), y)
t1 = refract((1.0, 0.0), (P0[0] / R, P0[1] / R), 1.0, n)
sp = -2 * (P0[0] * t1[0] + P0[1] * t1[1])
P1 = (P0[0] + sp * t1[0], P0[1] + sp * t1[1])
t2 = refract(t1, (-P1[0] / R, -P1[1] / R), n, 1.0)
xf = P1[0] - P1[1] * t2[0] / t2[1]
check('15.С2 фокус шара от центра (трассировка)', xf, n * R / (2 * (n - 1)), 1e-4)
