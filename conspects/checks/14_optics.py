ok = 0


def check(name, got, want, rel=1e-3):
    global ok
    assert abs(got - want) <= rel * max(1e-30, abs(want)), f'{name}: {got} ≠ {want}'
    ok += 1
    print(f'  ✓ {name}: {got:.6g}')


def lens_image(d, F, h=1.0):
    """Предмет высотой h на расстоянии d перед тонкой линзой. Возвращает (f, H) — положение и
    высоту изображения (f > 0 — за линзой). Два луча: через центр и параллельный оси."""
    # луч через центр: y = −(h/d)·x; параллельный оси после линзы: y = h − (h/F)·x (x — от линзы)
    x = h / (h / F - h / d)
    return x, -(h / d) * x


