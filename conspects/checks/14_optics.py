def prism_dev(i_deg, A=60, n=1.5):
    i = radians(i_deg); r1 = asin(sin(i) / n); r2 = radians(A) - r1
    if n * sin(r2) >= 1: return None
    return degrees(i + asin(n * sin(r2))) - A


