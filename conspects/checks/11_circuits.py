Q, q, dt = 0.0, 0.0, 1e-5
for _ in range(1000000):                                          # R = 1 кОм, τ = 0,1 с, 10 τ
    I = (10 - q / 1e-4) / 1e3; Q += I * I * 1e3 * dt; q += I * dt
check('16.Р1 тепло (по шагам), мДж', Q * 1e3, 5, 1e-3)
