check('17.С3 тепло', C0 * E * E * (eps - 1) ** 2 / 2, 8e-6)
check('17.С3 баланс: работа руки + W₀ = W + тепло + энергия в источник', 1e-5 + eps * C0 * E * E / 2, C0 * E * E / 2 + 8e-6 + (eps - 1) * C0 * E * E)

