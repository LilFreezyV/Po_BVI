"""Проверка всех чисел конспекта «Постоянный ток» (conspects/physics/11.html).

Цепи проверяются универсальным решателем методом узловых потенциалов (Гаусс), независимым от
формул конспекта; RC-цепи — пошаговым интегрированием.
"""
from math import exp, log, sqrt

ok = 0


def check(name, got, want, rel=1e-3):
    global ok
    assert abs(got - want) <= rel * max(1e-30, abs(want)), f'{name}: {got} ≠ {want}'
    ok += 1
    print(f'  ✓ {name}: {got:.6g}')


def solve(A, b):
    n = len(b); M = [list(r) + [b[i]] for i, r in enumerate(A)]
    for i in range(n):
        p = max(range(i, n), key=lambda r: abs(M[r][i])); M[i], M[p] = M[p], M[i]
        for r in range(n):
            if r != i:
                f = M[r][i] / M[i][i]; M[r] = [x - f * y for x, y in zip(M[r], M[i])]
    return [M[i][n] / M[i][i] for i in range(n)]


def nodes(n, edges, fixed):
    """edges: (a, b, R, E) — ветвь от a к b с ЭДС E (поднимает потенциал b) и сопротивлением R.
    fixed: {узел: потенциал}. Возвращает потенциалы всех узлов."""
    free = [i for i in range(n) if i not in fixed]; ix = {v: k for k, v in enumerate(free)}
    A = [[0.0] * len(free) for _ in free]; b = [0.0] * len(free)
    for a, c, R, E in edges:                                      # ток a → c: (φa + E − φc)/R
        g = 1 / R
        for u, v, sgn in ((a, c, 1), (c, a, -1)):                 # сумма вытекающих токов узла = 0
            if u in ix:
                A[ix[u]][ix[u]] += g
                if v in ix: A[ix[u]][ix[v]] -= g
                else: b[ix[u]] += g * fixed[v]
                b[ix[u]] -= sgn * E * g
    x = solve(A, b); phi = dict(fixed)
    for v, k in ix.items(): phi[v] = x[k]
    return phi


def req(n, edges, a, c):
    """Эквивалентное сопротивление между узлами a и c."""
    phi = nodes(n, [(u, v, R, 0) for u, v, R in edges], {a: 1.0, c: 0.0})
    I = sum((phi[u] - phi[v]) / R for u, v, R in edges if u == a) - sum((phi[u] - phi[v]) / R for u, v, R in edges if v == a)
    return 1 / I


