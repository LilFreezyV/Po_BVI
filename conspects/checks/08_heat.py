# -*- coding: utf-8 -*-
"""Проверка всех чисел конспекта «Тепловые явления» (conspects/physics/08.html).

Константы: вода c = 4200 Дж/(кг·К), лёд 2100, λ = 330 кДж/кг, L = 2,3 МДж/кг, алюминий 900,
железо 460. Балансы решаются вторым способом (пошаговым теплообменом или моделированием).
"""
from math import exp, log

ok = 0
cw, ci, lam, Lv = 4200, 2100, 330e3, 2.3e6


def check(name, got, want, rel=1e-3):
    global ok
    assert abs(got - want) <= rel * max(1, abs(want)), f'{name}: {got} ≠ {want}'
    ok += 1
    print(f'  ✓ {name}: {got:.6g}')


def exchange(bodies, steps=200000):
    """Тела (теплоёмкость, температура) обмениваются теплом малыми порциями до выравнивания."""
    bodies = [list(b) for b in bodies]
    for _ in range(steps):
        Tm = sum(C * T for C, T in bodies) / sum(C for C, _ in bodies)
        for b in bodies:
            b[1] += (Tm - b[1]) * 0.5
    return bodies[0][1]


print('01 Тепловой баланс')
check('1.Р1 температура смеси', (2 * 80 + 3 * 20) / 5, 44)
check('1.Р1 обмен порциями', exchange([(2 * cw, 80), (3 * cw, 20)], 50), 44)
check('1.С1 теплота', cw * 2 * 80, 672000)
T = (0.2 * cw * 20 + 0.1 * 900 * 20 + 0.1 * 460 * 100) / (0.2 * cw + 0.1 * 900 + 0.1 * 460)
check('1.С2 температура', T, 23.770)
check('1.С2 баланс', (0.2 * cw + 0.1 * 900) * (T - 20), 0.1 * 460 * (100 - T))
r = 10 / 70
T2 = ((1 + r) * 30 + r * 100) / (1 + 2 * r)                     # первый шарик остаётся в воде
check('1.С3 после второго шарика', T2, 37.778)
check('1.С3 = 340/9', T2, 340 / 9)

print('02 Динамическое равновесие')
check('2.Р1 температура на выходе', 10 + 5000 / (cw * 0.05), 33.810)
check('2.С1 смеситель', (0.1 * 60 + 0.15 * 10) / 0.25, 30)
check('2.С2 установившаяся', 20 + 1000 / 20, 70)
m, mu = 1, 0.01
t_th = m / mu * log(2)
check('2.С3 время (формула)', t_th, 69.315)
# моделирование перемешивания: dT = μ dt (80 − T)/m
Tt, t, dt = 20.0, 0.0, 1e-3
while Tt < 50:
    Tt += mu * dt * (80 - Tt) / m; t += dt
check('2.С3 время (моделирование)', t, 69.315, 1e-4)

print('03 Фазовые переходы')
give = 1 * cw * 20
check('3.Р1 теплота от воды до 0 °C', give, 84000)
check('3.Р1 растает льда', give / lam, 0.25455)
check('3.Р1 останется льда', 0.5 - give / lam, 0.24545)
check('3.С1 теплота', ci * 10 + lam, 351000)
T = (0.1 * Lv + 0.1 * cw * 100 + 1 * cw * 20) / (1.1 * cw)
check('3.С2 температура', T, 77.056)
check('3.С2 баланс', 0.1 * Lv + 0.1 * cw * (100 - T), cw * (T - 20))
Q = 2 * (ci * 20 + lam + cw * 100 + Lv)
check('3.С3 теплота', Q, 6.184e6)
check('3.С3 бензин', Q / (0.4 * 46e6), 0.33609)

print('04 Теплопроводность')
check('4.Р1 мощность', 0.7 * 10 * 30 / 0.5, 420)
check('4.С1 мощность', 400 * 1e-4 * 100 / 0.5, 8)
# остывание: время 80→50 и 50→35 при T₀ = 20
tau = 600 / log(2)
t1 = tau * log((80 - 20) / (50 - 20)); t2 = tau * log((50 - 20) / (35 - 20))
check('4.С2 время 50→35, мин', t2 / 60, 10)
Tt, t, dt = 50.0, 0.0, 1e-3
while Tt > 35:
    Tt -= dt * (Tt - 20) / tau; t += dt
check('4.С2 время (моделирование), мин', t / 60, 10, 1e-4)
R1, R2 = 0.2 / 0.7, 0.1 / 0.04
P = 30 / (R1 + R2)
check('4.С3 поток, Вт/м²', P, 10.769)
check('4.С3 температура на границе', 20 - P * R1, 16.923)
# 4.С3 разностной схемой: стена разбита на слои, в каждом узле поток слева = поток справа;
# систему уравнений решаем прогонкой
N1, N2 = 40, 20
g_ = [0.7 / (0.2 / N1)] * N1 + [0.04 / (0.1 / N2)] * N2         # теплопроводности участков κ/h
n = N1 + N2 - 1                                                  # внутренние узлы
a_ = [-g_[i] for i in range(n)]; c_ = [-g_[i + 1] for i in range(n)]; b_ = [g_[i] + g_[i + 1] for i in range(n)]
d_ = [0.0] * n; d_[0] += g_[0] * 20; d_[-1] += g_[-1] * -10
for i in range(1, n):                                            # прямой ход
    w_ = a_[i] / b_[i - 1]; b_[i] -= w_ * c_[i - 1]; d_[i] -= w_ * d_[i - 1]
x_ = [0.0] * n; x_[-1] = d_[-1] / b_[-1]
for i in range(n - 2, -1, -1):
    x_[i] = (d_[i] - c_[i] * x_[i + 1]) / b_[i]
Ts = [20.0] + x_ + [-10.0]
flux = [g_[i] * (Ts[i] - Ts[i + 1]) for i in range(N1 + N2)]
check('4.С3 поток (разностная схема)', sum(flux) / len(flux), 10.769, 1e-4)
check('4.С3 граница (разностная схема)', Ts[N1], 16.923, 1e-4)

print('05 Тепловые сети')
check('5.Р1 сопротивление', 1 + 0.5, 1.5)
check('5.С2 узел', 100 / 3, 33.333)
# мост: AB = R, BC = 2R, AD = 2R, DC = R, BD = R; A = 100, C = 0 (решаем итерациями)
B = D = 50.0
for _ in range(10000):
    B = (100 / 1 + D / 1 + 0 / 2) / (1 + 1 + 0.5)
    D = (100 / 2 + B / 1 + 0 / 1) / (0.5 + 1 + 1)
check('5.С3 узел B', B, 57.143)
check('5.С3 узел D', D, 42.857)
check('5.С3 поток через BD (на 1/R)', B - D, 14.286)
check('5.С3 эквивалентное сопротивление (в R)', 100 / ((100 - B) + (100 - D) / 2), 1.4)

print(f'\nВсе проверки пройдены: {ok}')
