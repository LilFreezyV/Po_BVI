"""Данные БВИ-навигатора: кто из вузов что даёт за перечневую олимпиаду по физике.

Состояние на 21 октября 2026. Что здесь факты и откуда они:

* уровень олимпиады — приказ Минобрнауки № 669 от 30.08.2025 (перечень на 2026/27);
* льготы вузов — правила приёма 2026 конкретного вуза (приложения с перечнями);
* даты туров — сайты олимпиад;
* «проект 2027» — проект изменений Порядка приёма № 171214 на regulation.gov.ru и
  опубликованные вузами проекты правил; это ещё не действующие нормы.

Правила приёма вузы обязаны опубликовать до 20 января, поэтому «проект 2027» будет
меняться. Перед подачей документов сверяйтесь с сайтом вуза: мы не отвечаем за
решения приёмной комиссии.

Как править: правьте этот файл и перезапускайте `python -m scripts.seed`. Сводная
таблица пересобирается целиком (delete + insert), так что удаления тоже отрабатывают.

Даты сезона — структурой (`stages`), а не текстом (с 2026-10-24): из неё строятся карточки
олимпиад, календарь «Ближайшие даты», обратный отсчёт на главной и еженедельное напоминание
бота о датах, которые пора уточнить. За страницами с датами (`dates_url`, по умолчанию —
`site_url`) каждый день следит проверка, см. app/date_watch.py.
"""

KINDS =("registration", "selection", "final")


def stage(kind, start=None, end=None, *, title="", note=None, approx=False, time=None, subject=None,
          settled=False):
    """Этап сезона.

    kind  — 'registration' | 'selection' | 'final' (строки «Регистрация / Отбор / Финал»);
    start, end — 'YYYY-MM-DD' (точная дата) или 'YYYY-MM' (известен только месяц), или None:
              только start — один день («4 октября») или «с …» у регистрации;
              только end — срок «до …»; без дат — этап известен, а сроки нет (тогда note);
    approx — дата ориентировочная или предварительная («ор. февраль 2027»);
    time   — время начала по Москве, 'ЧЧ:ММ' (время в других поясах пишите в note);
    subject — 'physics' | 'math', если этап только для одного предмета; None — общий;
    settled — точнее сроки не станут (например, их назначает каждый регион): бот не будет
              напоминать уточнить такую дату.
    """
    assert kind in KINDS, kind
    return {
        "kind": kind, "start": start, "end": end, "title": title, "note": note,
        "approx": approx, "time": time, "subject": subject, "settled": settled,
    }

