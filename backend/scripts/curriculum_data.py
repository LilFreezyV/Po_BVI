def iter_modules():
    """Плоский обход: (subject, grade, position, module) для каждого модуля."""
    for course in CURRICULUM:
        for position, module in enumerate(course["modules"]):
            yield course["subject"], course["grade"], position, module


def module_id(subject: str, grade: int, slug: str) -> str:
    return f"{subject}-{grade}-{slug}"


def lesson_id(subject: str, grade: int, number: int) -> str:
    return f"{subject}-{grade}-{number:02d}"
