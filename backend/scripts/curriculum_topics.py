def parse_ref(ref: str) -> tuple[int, int]:
    grade, number = ref.split(".")
    return int(grade), int(number)


def auto_topics(subject: str, curriculum) -> list[dict]:
    """Раскладка «тема → подтемы» для предмета, у которого нет ручной (сейчас — математика).

    Темы плана повторяются из класса в класс («Планиметрия» есть в 9, 10 и 11), поэтому
    склеиваем их по slug в порядке первого появления, а подтемы внутри идут по классам.
    Ручная склейка одинаковых подтем, как у физики в TOPICS, тут не нужна: в плане по
    математике названия занятий не повторяются.
    """
    topics: dict[str, dict] = {}
    for course in curriculum:
        if course["subject"] != subject:
            continue
        for module in course["modules"]:
            topic = topics.setdefault(module["slug"], {"slug": module["slug"], "title": module["title"], "lessons": []})
            for number, *_ in module["lessons"]:
                topic["lessons"].append((None, [f"{course['grade']}.{number}"]))
    return list(topics.values())
